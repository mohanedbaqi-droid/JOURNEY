#!/usr/bin/env node
const assert=require('node:assert/strict');
const Sim=require('../../PunisherAndroid/app/src/main/assets/simulator.js');
const id='demo-v1',second='demo-v2';
let a=Sim.get(id);
assert.equal(a.mode,'simulation');
assert.equal(a.locked,true);
assert.equal(a.rpm,0);
assert.equal(a.gpsValid,true);
assert.equal(a.dtcs.length,0);
assert.equal(Sim.execute(id,'unlock').ok,true);
assert.equal(Sim.get(id).locked,false);
assert.equal(Sim.get(second).locked,true,'Vehicle isolation');
assert.equal(Sim.execute(id,'start').ok,true);
assert.equal(Sim.get(id).rpm,780);
assert.equal(Sim.execute(id,'stop').ok,true);
assert.equal(Sim.get(id).rpm,0);
assert.equal(Sim.execute(id,'unknown').ok,false,'Unknown commands fail closed');
Sim.setSensors(id,{doorsClosed:false});
assert.equal(Sim.execute(id,'lock').reason,'door-open');
assert.equal(Sim.execute(id,'start').reason,'safety-guard');
Sim.setSensors(id,{doorsClosed:true,connected:false});
assert.equal(Sim.execute(id,'start').reason,'demo-disconnected');
Sim.setSensors(id,{connected:true,speedKmh:30,parked:false});
assert.equal(Sim.execute(id,'start').reason,'safety-guard');
assert.equal(Sim.execute(id,'stop').reason,'vehicle-moving');
assert.throws(()=>Sim.setSensors(id,{privateData:100}));
assert.throws(()=>Sim.setSensors(id,{batteryV:'invalid'}));
const cloned=Sim.get(id);cloned.locked=false;assert.equal(Sim.get(id).locked,true,'State clone protects store');
assert.equal(Sim.reset(id).seq,0);
console.log('PASS: offline simulator, vehicle isolation, telemetry, safe command rejection');
